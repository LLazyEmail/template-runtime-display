import { RenderError } from '@llazyemail/render-template';
import { fromError } from '../runtime/result';
import type { PartStatus, PartTrace, RenderResult } from '../runtime/types';
import { escapeHtml } from '../utils/escape';
import { measureSize } from '../quality/size';
import type { SizeReport } from '../quality/size';
import { toText } from '../quality/text';
import { diffRenders, trimContext } from './diff';
import type { DiffLine, RenderDiff } from './diff';
import { withScheme } from './scheme';
import { STYLES } from './styles';

export interface InspectOptions {
  /** Page title. Defaults to `Inspect · <template id>`. */
  title?: string;
  /** An earlier render of the same template. Adds a "what changed" section. */
  compareTo?: RenderResult | RenderError;
}

/**
 * Build one self-contained HTML page that shows a render: a timeline of the
 * parts, which one broke and why, each part's output next to its source, and
 * the final document in a sandboxed frame at three widths.
 *
 * The page has no scripts and loads nothing from the network. Rendered HTML
 * only appears inside `sandbox=""` frames and escaped `<pre>` blocks, so a
 * hostile part cannot run code in the report.
 */
export function inspect(input: RenderResult | RenderError, options: InspectOptions = {}): string {
  const thrown = input instanceof RenderError ? input : undefined;
  const result = thrown ? fromError(thrown) : (input as RenderResult);
  const title = options.title ?? `Inspect · ${result.templateId}`;
  const diff = options.compareTo ? diffRenders(toResult(options.compareTo), result) : undefined;

  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<meta name="color-scheme" content="light dark">',
    `<title>${escapeHtml(title)}</title>`,
    `<style>${STYLES}</style>`,
    '</head>',
    '<body>',
    '<main class="page">',
    header(result),
    failureBanner(result, thrown),
    timeline(result.parts),
    diff ? diffSection(diff) : '',
    documentSection(result),
    sizeSection(result),
    textSection(result),
    partsSection(result.parts),
    '<p class="foot">Generated by @llazyemail/template-runtime-display</p>',
    '</main>',
    '</body>',
    '</html>',
  ]
    .filter((chunk) => chunk !== '')
    .join('\n');
}

function toResult(value: RenderResult | RenderError): RenderResult {
  return value instanceof RenderError ? fromError(value) : value;
}

function fmtMs(ms: number): string {
  // Returned as HTML, so the less-than sign is already escaped.
  if (ms < 0.01) return '&lt;0.01ms';
  return `${ms.toFixed(ms < 1 ? 2 : 1)}ms`;
}

function fmtChars(chars: number): string {
  return `${chars.toLocaleString('en-US')} chars`;
}

function chip(status: PartStatus): string {
  return `<span class="chip s-${escapeHtml(status)}">${escapeHtml(status)}</span>`;
}

function header(result: RenderResult): string {
  const totalMs = result.parts.reduce((sum, part) => sum + part.ms, 0);
  const slowest = result.parts.reduce<PartTrace | undefined>(
    (best, part) => (part.ms > (best?.ms ?? 0) ? part : best),
    undefined,
  );
  const facts = [
    `${result.parts.length} ${result.parts.length === 1 ? 'part' : 'parts'}`,
    fmtChars(result.html.length),
    `${fmtMs(totalMs)} total`,
    ...(slowest ? [`slowest: ${escapeHtml(slowest.id)} (${fmtMs(slowest.ms)})`] : []),
  ];

  return [
    '<header class="head">',
    `<div><p class="eyebrow">Template</p><h1>${escapeHtml(result.templateId)}</h1></div>`,
    `<span class="verdict ${result.ok ? 'v-ok' : 'v-bad'}">${result.ok ? 'OK' : 'FAILED'}</span>`,
    `<p class="facts">${facts.join(' · ')}</p>`,
    '</header>',
  ].join('\n');
}

function failureBanner(result: RenderResult, thrown: RenderError | undefined): string {
  if (thrown) {
    return `<div class="banner" role="alert"><strong>Render threw in part “${escapeHtml(thrown.partId)}”</strong><pre>${escapeHtml(thrown.message)}</pre></div>`;
  }
  if (result.composeError) {
    const { name, message } = result.composeError;
    return `<div class="banner" role="alert"><strong>compose failed</strong><pre>${escapeHtml(name)}: ${escapeHtml(message)}</pre></div>`;
  }
  const broken = result.parts.filter((part) => part.status === 'error');
  if (broken.length === 0) return '';
  const lines = broken.map(
    (part) =>
      `<li><a href="#part-${result.parts.indexOf(part)}">${escapeHtml(part.id)}</a>: ${escapeHtml(part.error?.name ?? 'Error')}: ${escapeHtml(part.error?.message ?? '')}</li>`,
  );
  return `<div class="banner" role="alert"><strong>${broken.length === 1 ? '1 part broke' : `${broken.length} parts broke`}</strong><ul>${lines.join('')}</ul></div>`;
}

function timeline(parts: readonly PartTrace[]): string {
  if (parts.length === 0) return '';
  // Parts usually run in microseconds, so bars show output size. Time stays in the text.
  const maxChars = Math.max(...parts.map((part) => part.chars));
  const rows = parts.map((part, index) => {
    const width = maxChars > 0 ? Math.max(2, (part.chars / maxChars) * 100) : 2;
    const bar =
      part.status === 'skipped'
        ? '<span class="track"><span class="bar skipped"></span></span>'
        : `<span class="track"><span class="bar b-${escapeHtml(part.status)}" style="--w:${width.toFixed(1)}%"></span></span>`;
    return `<a class="row" href="#part-${index}"><span class="name">${escapeHtml(part.id)}</span>${bar}<span class="stat">${chip(part.status)} ${fmtChars(part.chars)} · ${fmtMs(part.ms)}</span></a>`;
  });
  return `<section class="card"><h2>Output by part</h2><div class="rows">${rows.join('')}</div></section>`;
}

function documentSection(result: RenderResult): string {
  if (result.html === '') {
    return '<section class="card"><h2>Document</h2><p class="note">No document. Compose did not run or produced nothing.</p></section>';
  }
  return [
    '<section class="card">',
    '<h2>Document</h2>',
    '<div class="viewport">',
    '<input type="radio" name="vp" id="vp-full" checked><label for="vp-full">Full</label>',
    '<input type="radio" name="vp" id="vp-tablet"><label for="vp-tablet">Tablet 768</label>',
    '<input type="radio" name="vp" id="vp-mobile"><label for="vp-mobile">Mobile 375</label>',
    '<input type="radio" name="sc" id="sc-light" checked><label for="sc-light" class="first">Light</label>',
    '<input type="radio" name="sc" id="sc-dark"><label for="sc-dark">Dark</label>',
    `<div class="stage"><iframe sandbox="" referrerpolicy="no-referrer" title="Rendered document" class="doc-light" srcdoc="${escapeHtml(withScheme(result.html, 'light'))}"></iframe><iframe sandbox="" referrerpolicy="no-referrer" title="Rendered document, dark" class="doc-dark" srcdoc="${escapeHtml(withScheme(result.html, 'dark'))}"></iframe></div>`,
    '<p class="note">Light and Dark set the preview\'s color scheme, like a client that supports <code>color-scheme</code>. Your own <code>prefers-color-scheme</code> styles follow your system setting.</p>',
    '</div>',
    '</section>',
  ].join('\n');
}

function partsSection(parts: readonly PartTrace[]): string {
  if (parts.length === 0) return '';
  return `<section class="card"><h2>Parts</h2>${parts.map((part, index) => partCard(part, index, parts.length)).join('\n')}</section>`;
}

function partCard(part: PartTrace, index: number, count: number): string {
  const open = part.status === 'error' ? ' open' : '';
  return [
    `<details class="part" id="part-${index}"${open}>`,
    `<summary><span class="name">${escapeHtml(part.id)}</span> ${chip(part.status)} <span class="meta">${fmtChars(part.chars)} · ${fmtMs(part.ms)}</span></summary>`,
    partBody(part),
    partNav(index, count),
    '</details>',
  ].join('\n');
}

function partBody(part: PartTrace): string {
  if (part.status === 'skipped') {
    return '<p class="note">Skipped because an earlier part failed.</p>';
  }
  const error = part.error
    ? `<div class="banner inline"><strong>${escapeHtml(part.error.name)}</strong><pre>${escapeHtml(part.error.message)}</pre></div>`
    : '';
  if (part.html === '') {
    return `${error}<p class="note">${part.status === 'error' ? 'Rendered nothing because it failed.' : 'Rendered an empty string.'}</p>`;
  }
  return [
    error,
    `<iframe class="frag" sandbox="" referrerpolicy="no-referrer" title="Preview of ${escapeHtml(part.id)}" srcdoc="${escapeHtml(part.html)}"></iframe>`,
    `<pre class="src"><code>${escapeHtml(part.html)}</code></pre>`,
  ].join('\n');
}

function diffSection(diff: RenderDiff): string {
  if (!diff.changed) {
    return '<section class="card"><h2>Changes</h2><p class="note">No changes since the previous render.</p></section>';
  }
  const changes = diff.parts
    .filter((part) => part.change !== 'unchanged')
    .map((part) => {
      const sign = part.charsDelta > 0 ? '+' : '';
      return `<li><span class="name">${escapeHtml(part.id)}</span> <span class="chip c-${part.change}">${part.change}</span> <span class="meta">${sign}${part.charsDelta} chars</span></li>`;
    });
  const lines = trimContext(diff.lines).map(diffLine);
  return `<section class="card"><h2>Changes since the previous render</h2><ul class="changes">${changes.join('')}</ul><pre class="diff"><code>${lines.join('')}</code></pre></section>`;
}

function diffLine(line: DiffLine): string {
  const sign = line.kind === 'add' ? '+' : line.kind === 'del' ? '-' : ' ';
  return `<span class="d-${line.kind}">${sign} ${escapeHtml(line.text)}</span>`;
}

function partNav(index: number, count: number): string {
  const prev = index > 0 ? `<a href="#part-${index - 1}">&uarr; previous</a>` : '';
  const next = index < count - 1 ? `<a href="#part-${index + 1}">next &darr;</a>` : '';
  return prev === '' && next === '' ? '' : `<nav class="pn">${prev}${next}</nav>`;
}

function fmtBytes(bytes: number): string {
  return bytes < 1024 ? `${bytes} B` : `${(bytes / 1024).toFixed(1)} KB`;
}

const RISK_CHIP: Record<SizeReport['clipRisk'], string> = {
  ok: 's-ok',
  near: 's-empty',
  over: 's-error',
};

function sizeSection(result: RenderResult): string {
  if (result.html === '') return '';
  const size = measureSize(result);
  const fill = Math.min(100, (size.bytes / size.limit) * 100).toFixed(1);
  const mark = ((size.nearLimit / size.limit) * 100).toFixed(1);
  const largest = size.perPart
    .slice(0, 5)
    .map(
      (part) =>
        `<li><span class="name">${escapeHtml(part.id)}</span> <span class="meta">${fmtBytes(part.bytes)}</span></li>`,
    );
  const warnings = size.warnings.map((warning) => `<li>${escapeHtml(warning)}</li>`);

  return [
    '<section class="card">',
    '<h2>Size</h2>',
    `<p class="sizeline"><strong>${fmtBytes(size.bytes)}</strong> of ${fmtBytes(size.limit)} <span class="chip ${RISK_CHIP[size.clipRisk]}">${size.clipRisk}</span></p>`,
    `<div class="meter" role="img" aria-label="${fmtBytes(size.bytes)} of ${fmtBytes(size.limit)}"><span class="fill r-${size.clipRisk}" style="--w:${fill}%"></span><span class="mark" style="--at:${mark}%"></span></div>`,
    '<p class="note">Gmail clips a message over this size and hides the rest, including the unsubscribe link. The line marks where the warning starts.</p>',
    warnings.length > 0 ? `<ul class="warns">${warnings.join('')}</ul>` : '',
    `<ul class="sizes">${largest.join('')}</ul>`,
    '</section>',
  ]
    .filter((chunk) => chunk !== '')
    .join('\n');
}

function textSection(result: RenderResult): string {
  if (result.html === '') return '';
  const text = toText(result.html);
  const lines = text === '' ? 0 : text.trimEnd().split('\n').length;
  return [
    '<section class="card">',
    `<details class="plain"><summary><span class="name">Plain-text version</span> <span class="meta">${lines} ${lines === 1 ? 'line' : 'lines'} · click the text to select it all</span></summary>`,
    text === ''
      ? '<p class="note">The document has no text.</p>'
      : `<pre class="src"><code>${escapeHtml(text)}</code></pre>`,
    '</details>',
    '</section>',
  ].join('\n');
}
